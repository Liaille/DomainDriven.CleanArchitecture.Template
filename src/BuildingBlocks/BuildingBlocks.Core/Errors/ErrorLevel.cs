namespace BuildingBlocks.Core.Errors;

/// <summary>
/// 系统统一错误级别枚举
/// 用于标识错误、日志、异常信息的严重程度，统一全系统的级别标准
/// </summary>
public enum ErrorLevel
{
    /// <summary>
    /// 信息级别
    /// 用于记录常规运行状态、业务流程正常执行、非关键操作的提示信息
    /// 无任何异常，仅用于追踪系统正常运行轨迹
    /// </summary>
    Info = 0,

    /// <summary>
    /// 警告级别
    /// 用于记录潜在风险、非预期但不影响主流程的异常、可自动恢复的小问题
    /// 系统仍可正常运行，无需人工干预，但需要关注
    /// </summary>
    Warn = 1,

    /// <summary>
    /// 错误级别
    /// 用于记录业务逻辑执行失败、功能异常、无法自动处理的问题
    /// 影响当前操作/功能，但不导致整个系统崩溃，需要人工排查修复
    /// </summary>
    Error = 2,

    /// <summary>
    /// 致命级别
    /// 用于记录系统崩溃、核心服务不可用、数据严重损坏等极端严重问题
    /// 导致系统整体无法正常运行，必须立即紧急处理
    /// </summary>
    Fatal = 3
}
